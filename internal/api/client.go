func truncate(b []byte, n int) string {
	if len(b) <= n {
		return string(b)
	}
	return string(b[:n]) + "..."
}

// osUserAgent mirrors the stock client's login UA format:
// "<pretty product name>, <kernel version>".
// On Linux, prettyProductName comes from /etc/os-release and kernelVersion
// from uname(2). Matches QSysInfo::prettyProductName() + QSysInfo::kernelVersion().
func osUserAgent() string {
	pretty := ""
	if b, err := os.ReadFile("/etc/os-release"); err == nil {
		for _, line := range strings.Split(string(b), "\n") {
			if strings.HasPrefix(line, "PRETTY_NAME=") {
				pretty = strings.Trim(strings.TrimPrefix(line, "PRETTY_NAME="), `"`)
				break
			}
		}
	}
	kernel := "unknown"
	if err := syscall.Uname(&sysUts); err == nil {
		kernel = charsToString(sysUts.Release[:])
	}
	if pretty == "" {
		pretty = "Linux"
	}
	return pretty + ", " + kernel
}

var sysUts syscall.Utsname

func charsToString(ca []int8) string {
	b := make([]byte, 0, len(ca))
	for _, c := range ca {
		if c == 0 {
			break
		}
		b = append(b, byte(c))
	}
	return string(b)
}
