// rawAuthed performs an authenticated request byte-for-byte like the stock
// client: raw uTLS/HTTP connection, lowercase satoken header + cookie,
// Connection: Keep-Alive, header order as captured.
func (c *Client) rawAuthed(method, path string, body []byte) ([]byte, error) {
	u, err := url.Parse(c.BaseURL)
	if err != nil {
		return nil, err
	}
	addr := net.JoinHostPort(u.Hostname(), u.Port())
	dial := dialLogin
	if c.DialOverride != nil {
		dial = c.DialOverride
	}
	conn, err := dial(u.Hostname(), addr)
	if err != nil {
		return nil, err
	}
	defer conn.Close()
	conn.SetDeadline(time.Now().Add(20 * time.Second))
	var b bytes.Buffer
	fmt.Fprintf(&b, "%s %s HTTP/1.1\r\n", method, path)
	fmt.Fprintf(&b, "Host: benshulinux.org:8443\r\n")
	if c.Token != "" {
		fmt.Fprintf(&b, "satoken: %s\r\n", c.Token)
		fmt.Fprintf(&b, "Cookie: satoken=%s\r\n", c.Token)
	}
	fmt.Fprintf(&b, "Connection: Keep-Alive\r\n")
	fmt.Fprintf(&b, "Accept-Encoding: gzip, deflate\r\n")
	fmt.Fprintf(&b, "Accept-Language: en,*\r\n")
	fmt.Fprintf(&b, "User-Agent: Mozilla/5.0\r\n")
	if body != nil {
		fmt.Fprintf(&b, "Content-Type: application/json\r\n")
		fmt.Fprintf(&b, "Content-Length: %d\r\n", len(body))
	}
	b.WriteString("\r\n")
	if body != nil {
		b.Write(body)
	}
	if _, err := conn.Write(b.Bytes()); err != nil {
		return nil, err
	}
	resp, err := http.ReadResponse(bufio.NewReader(conn), nil)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	rbody := resp.Body
	if resp.Header.Get("Content-Encoding") == "gzip" {
		gz, err := gzip.NewReader(resp.Body)
		if err != nil {
			return nil, err
		}
		defer gz.Close()
		rbody = gz
	}
	payload, err := io.ReadAll(rbody)
	if err != nil {
		return nil, err
	}
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("api: %s: HTTP %d: %s", path, resp.StatusCode, truncate(payload, 200))
	}
	return payload, nil
}

// SessionKeyHex returns the hex form of the session key held by this client
// (the L1 password for playerKey/ebookKey envelopes). Empty unless a login
// happened on this client instance.
func (c *Client) SessionKeyHex() string {
	return protocol.SessionKeyHex(c.SessionKeyRaw)
}

// PlayerKey decrypts a video's playerKey envelope with this client's
// session key and returns the 32-hex-char CENC content key (ffmpeg's
// -decryption_key value). Requires that Login (not just -token) ran on
// this client instance.
func (c *Client) PlayerKey(v *protocol.Video) ([]byte, error) {
	if len(c.SessionKeyRaw) != 16 {
		return nil, fmt.Errorf("api: no session key on this client (login must run in-process, -token is not enough)")
	}
	return protocol.DecryptPlayerKey(v.PlayerKey, c.SessionKeyHex())
}

// CourseKey decrypts a course detail's ebookKey envelope with this client's
// session key and returns the 32-hex-char course key. Requires an
// in-process login.
func (c *Client) DecryptEBookKeyRaw(ebookKeyB64 string) ([]byte, error) {
	if len(c.SessionKeyRaw) != 16 {
		return nil, fmt.Errorf("api: no session key on this client (login must run in-process, -token is not enough)")
	}
	return protocol.DecryptEBookKey(ebookKeyB64, c.SessionKeyHex())
}

