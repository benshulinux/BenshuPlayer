// Client talks to one server endpoint.
type Client struct {
	BaseURL   string
	HTTP      *http.Client
	Token     string // satoken, set after a successful login
	MachineID string
	// UserAgent is sent on non-login requests. The stock client sends
	// Qt's default "Mozilla/5.0" there; Go's default differs, so be
	// explicit to keep traffic indistinguishable.
	UserAgent string

	// SessionKeyRaw is the 16-byte random session key wrapped by RSA in
	// the login `data` field. Per-login, generated by BuildLogin.
	SessionKeyRaw []byte

	// DialOverride replaces the uTLS dial used by the login chain; tests
	// use it to reach a plain-HTTP replay server. Nil = production uTLS.
	DialOverride func(serverName, addr string) (net.Conn, error)

	// LoginStepDelay is the pacing between login-chain requests (stock
	// client: ~15s auto-login, 3-6s dialog). Zero it in tests.
	LoginStepDelay time.Duration
}

// httpClient returns the shared HTTP client configuration.
//
// Two stock-client parity points are pinned here:
//   - HTTP/1.1 only: Qt5 QNetworkAccessManager has no HTTP/2 support, so
//     ForceAttemptHTTP2=false (the uTLS hello below also advertises no
//     ALPN, which rules h2 out at the TLS layer).
//   - TLS fingerprint: the handshake is done by uTLS replaying the exact
//     ClientHello captured from the stock binary (see tlsfingerprint).
func httpClient(serverName string, roots *x509.CertPool) *http.Client {
	return &http.Client{
		Timeout: 20 * time.Second, // stock client: 20s, no retry
		Transport: &http.Transport{
			ForceAttemptHTTP2: false,
			DialTLSContext:    tlsfingerprint.DialTLSContext(serverName, roots),
		},
	}
}

// serverNameFromURL extracts the bare hostname (no port) used for SNI.
func serverNameFromURL(baseURL string) string {
	u, err := url.Parse(baseURL)
	if err != nil {
		return baseURL
	}
	return u.Hostname()
}

// NewClient creates a client for the default production endpoint.
func NewClient() (*Client, error) {
	mid, err := machineid.LinuxMachineID()
	if err != nil {
		return nil, fmt.Errorf("api: %w", err)
	}
	return &Client{
		BaseURL:        protocol.DefaultServerURL,
		HTTP:           httpClient(serverNameFromURL(protocol.DefaultServerURL), nil),
		MachineID:      mid,
		UserAgent:      "Mozilla/5.0",
		LoginStepDelay: loginStepDelayDefault,
	}, nil
}

