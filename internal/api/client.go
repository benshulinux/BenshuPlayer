// ScreenRecord fetches the server's screen-recording detection config.
//
// Observed behavior (105/105 captures, 2026-10-29): the stock client
// calls this immediately after login (login → get/courses → get_screen_record),
// carries the satoken ONLY as a Cookie (never as a header — unlike every
// other authed endpoint), and the response is always
// {"code":200,"msg":"操作成功","data":[]} (empty config list).
func (c *Client) ScreenRecord() ([]map[string]any, error) {
	req, err := http.NewRequest("GET", c.url("api/common/get_screen_record?os=Linux"), nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", c.UserAgent)
	req.Header.Set("Accept-Encoding", "gzip, deflate")
	req.Header.Set("Accept-Language", "en,*")
	if c.Token != "" {
		// Cookie only — mirrors the stock client exactly.
		req.AddCookie(&http.Cookie{Name: protocol.TokenHeader, Value: c.Token})
	}
	resp, err := c.HTTP.Do(req)
	if err != nil {
		return nil, fmt.Errorf("api: get_screen_record: %w", err)
	}
	defer resp.Body.Close()
	body := resp.Body
	if resp.Header.Get("Content-Encoding") == "gzip" {
		gz, err := gzip.NewReader(resp.Body)
		if err != nil {
			return nil, fmt.Errorf("api: get_screen_record: gzip: %w", err)
		}
		defer gz.Close()
		body = gz
	}
	payload, err := io.ReadAll(body)
	if err != nil {
		return nil, fmt.Errorf("api: get_screen_record: read: %w", err)
	}
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("api: get_screen_record: HTTP %d: %s", resp.StatusCode, truncate(payload, 200))
	}
	var env protocol.Envelope
	if err := json.Unmarshal(payload, &env); err != nil {
		return nil, fmt.Errorf("api: get_screen_record: bad envelope JSON: %w", err)
	}
	if env.Code != 200 {
		return nil, fmt.Errorf("api: get_screen_record: code=%d msg=%s", env.Code, env.Msg)
	}
	var cfg []map[string]any
	if err := json.Unmarshal(env.Data, &cfg); err != nil {
		return nil, fmt.Errorf("api: get_screen_record: data: %w", err)
	}
	return cfg, nil
}

// ReportWatch reports playback progress (stock client sends this per video).
// Observed pattern (2026-10-29 captures): the player fires
// report_watch{watchSeconds: 1} the moment a video is opened, then more
// reports as playback proceeds. Callers can mirror this on open.
func (c *Client) ReportWatch(courseID, studentID, videoIndex, watchSeconds int) error {
	body := map[string]any{
		"courseId":     courseID,
		"machineId":    c.MachineID,
		"os":           "linux",
		"studentId":    studentID,
		"videoIndex":   videoIndex,
		"watchSeconds": watchSeconds,
	}
	env, err := c.do("POST", "api/common/report_watch", body, false)
	if err != nil {
		return err
	}
	if env.Code != 200 {
		return fmt.Errorf("api: report_watch: code=%d msg=%s", env.Code, env.Msg)
	}
	return nil
}

