func (c *Client) url(path string) string {
	return strings.TrimRight(c.BaseURL, "/") + "/" + strings.TrimLeft(path, "/")
}

// do issues a request and decodes the Envelope, checking code == 200.
// (check_student_phone_password / check_send_sms_verify answer with
// code 0 instead — callers of those use doRaw.)
func (c *Client) do(method, path string, body any, loginUA bool) (*protocol.Envelope, error) {
	payload, err := c.doRaw(method, path, body, loginUA)
	if err != nil {
		return nil, err
	}
	var env protocol.Envelope
	if err := json.Unmarshal(payload, &env); err != nil {
		return nil, fmt.Errorf("api: %s: bad envelope JSON: %w", path, err)
	}
	return &env, nil
}

// doRaw performs the HTTP round-trip and returns the raw body.
// Auth (satoken) is attached when the client holds a token. Login-chain
// requests get the kernel/OS User-Agent; everything else gets UserAgent.
func (c *Client) doRaw(method, path string, body any, loginUA bool) ([]byte, error) {
	var reader io.Reader
	if body != nil {
		b, err := json.Marshal(body)
		if err != nil {
			return nil, err
		}
		reader = bytes.NewReader(b)
	}
	req, err := http.NewRequest(method, c.url(path), reader)
	if err != nil {
		return nil, err
	}
	// Header parity with the stock client (captured keyed requests):
	// Content-Type only on requests with a body; Accept-Encoding
	// "gzip, deflate"; Accept-Language "en,*" on every request.
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	req.Header.Set("Accept-Encoding", "gzip, deflate")
	req.Header.Set("Accept-Language", "en,*")
	if loginUA {
		req.Header.Set("User-Agent", osUserAgent())
	} else {
		req.Header.Set("User-Agent", c.UserAgent)
	}
	if c.Token != "" {
		req.Header.Set(protocol.TokenHeader, c.Token)
		// The stock client also carries the token as a cookie.
		req.AddCookie(&http.Cookie{Name: protocol.TokenHeader, Value: c.Token})
	}
	resp, err := c.HTTP.Do(req)
	if err != nil {
		return nil, fmt.Errorf("api: %s: %w", path, err)
	}
	defer resp.Body.Close()
	// The stock client sets Accept-Encoding itself and decompresses its own
	// gzip bodies; Go disables transparent gzip when the header is set
	// manually, so mirror that behavior explicitly.
	rbody := resp.Body
	if resp.Header.Get("Content-Encoding") == "gzip" {
		gz, err := gzip.NewReader(resp.Body)
		if err != nil {
			return nil, fmt.Errorf("api: %s: gzip: %w", path, err)
		}
		defer gz.Close()
		rbody = gz
	}
	payload, err := io.ReadAll(rbody)
	if err != nil {
		return nil, fmt.Errorf("api: %s: read: %w", path, err)
	}
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("api: %s: HTTP %d: %s", path, resp.StatusCode, truncate(payload, 200))
	}
	return payload, nil
}

// loginStepDelayDefault mirrors the stock client's pacing between
// login-chain requests: the auto-login flow (login.conf at startup) spaces
// the pre-checks and the login POST ~15s apart (measured from MITM
// captures, e.g. 05:37:52 → 05:38:07 → 05:38:22 on 2026-10-30); the dialog
// flow uses 3-6s gaps. Back-to-back chains are a visible scraper
// signature.
const loginStepDelayDefault = 15 * time.Second

// BuildLogin prepares a LoginRequest: a fresh 16-byte session key whose
// 32-char hex form is wrapped with the embedded RSA public key (PKCS#1
// v1.5). Pinned by disassembly of sub_335040 (call site 0x335313): the
// RSA input is UTF8(QString at manager+0x30) = the hex STRING (32 bytes),
// NOT the raw 16 bytes — the server unwraps and validates the plaintext
// format, which marks the session as a real client (entitled to keyed
// playerKey envelopes).
func (c *Client) BuildLogin(phone, password string) (*protocol.LoginRequest, error) {
	hexKey, _, err := crypto.NewSessionKey()
	if err != nil {
		return nil, err
	}
	pub, err := crypto.RSAPublicKey()
	if err != nil {
		return nil, err
	}
	blob, err := crypto.RSAPKCS1v15Encrypt(pub, []byte(hexKey)) // misnamed: RSA-OAEP-SHA1
	if err != nil {
		return nil, err
	}
	c.SessionKeyRaw, err = hex.DecodeString(hexKey)
	if err != nil {
		return nil, err
	}
	return &protocol.LoginRequest{
		Data:      base64.StdEncoding.EncodeToString(blob),
		MachineID: c.MachineID,
		Password:  password,
		PhoneNo:   phone,
	}, nil
}

// Login performs the full login flow and stores the satoken.
//
// The login chain (check_student_phone_password → check_send_sms_verify →
// login) is sent byte-for-byte like the stock client over ONE uTLS
// connection: exact header order, explicit Connection: Keep-Alive, and
// the kernel User-Agent on the login POST only. Observed 2026-10-30: a
// token issued to a Go-transport login got empty playerKeys, while the
// same requests with a stock-client-issued token got keyed envelopes —
// i.e. the server stamps the session's key-issuance entitlement at login,
// so byte-level login parity is what keeps the two clients
// indistinguishable.
func (c *Client) Login(phone, password string) (*protocol.LoginData, error) {
	u, err := url.Parse(c.BaseURL)
	if err != nil {
		return nil, err
	}
	addr := net.JoinHostPort(u.Hostname(), u.Port())
	dial := dialLogin
	if c.DialOverride != nil {
		dial = c.DialOverride
	}
	// The server answers every login-chain response with Connection: close
	// (captured), so — like the stock client — each request opens a fresh
	// connection.
	post := func(path, userAgent string, uaLast bool, body []byte) ([]byte, error) {
		conn, err := dial(u.Hostname(), addr)
		if err != nil {
			return nil, err
		}
		defer conn.Close()
		// The stock client times out after 20s with no retry; mirror that
		// on the raw path too (net.Dial alone has no deadline).
		conn.SetDeadline(time.Now().Add(20 * time.Second))
		return loginPost(conn, path, "application/json", userAgent, uaLast, body)
	}

	marshal := qtIndentedJSON

	// 1. Pre-check: password. UA = Mozilla/5.0 (last header, stock order).
	body1 := marshal([][2]string{
		{"machineId", c.MachineID}, {"password", password},
		{"phoneNo", phone}, {"version", protocol.Version}})
	if _, err := post("/api/common/check_student_phone_password", "Mozilla/5.0", true, body1); err != nil {
		return nil, fmt.Errorf("api: pre-check password: %w", err)
	}
	time.Sleep(c.LoginStepDelay)
	// 2. Pre-check: SMS verify gate.
	body2 := marshal([][2]string{
		{"data", "0"}, {"machineId", c.MachineID},
		{"phoneNo", phone}, {"version", protocol.Version}})
	if _, err := post("/api/common/check_send_sms_verify", "Mozilla/5.0", true, body2); err != nil {
		return nil, fmt.Errorf("api: pre-check sms: %w", err)
	}
	time.Sleep(c.LoginStepDelay)

	// 3. Login proper with the custom OS/kernel User-Agent (stock puts the
	// User-Agent after Content-Type here).
	req, err := c.BuildLogin(phone, password)
	if err != nil {
		return nil, err
	}
	payload, err := post("/api/common/login", osUserAgent(), false, marshal([][2]string{
		{"data", req.Data}, {"machineId", req.MachineID},
		{"password", req.Password}, {"phoneNo", req.PhoneNo}}))
	if err != nil {
		return nil, err
	}
	var env protocol.Envelope
	if err := json.Unmarshal(payload, &env); err != nil {
		return nil, fmt.Errorf("api: login: bad envelope JSON: %w", err)
	}
	if env.Code != 200 {
		return nil, fmt.Errorf("api: login rejected: code=%d msg=%s", env.Code, env.Msg)
	}

	// 4. Parse and validate the data object.
	var data protocol.LoginData
	if err := json.Unmarshal(env.Data, &data); err != nil {
		return nil, fmt.Errorf("api: login data: %w", err)
	}
	c.Token = data.TokenValue
	return &data, nil
}

// dialLogin dials the server for the login chain. When the process proxy
// env is set (as when the stock client is launched under a proxy), the
// connection goes through a CONNECT tunnel; otherwise it dials directly.
// Either way the uTLS byte-exact ClientHello is applied end-to-end.
func dialLogin(serverName, addr string) (net.Conn, error) {
	pu := os.Getenv("https_proxy")
	if pu == "" {
		pu = os.Getenv("HTTP_PROXY")
	}
	if pu == "" {
		pu = os.Getenv("http_proxy")
	}
	if pu == "" {
		return tlsfingerprint.DialTLS(serverName, addr)
	}
	for _, e := range strings.Split(os.Getenv("no_proxy"), ",") {
		if strings.TrimSpace(e) == serverName {
			return tlsfingerprint.DialTLS(serverName, addr)
		}
	}
	u, err := url.Parse(pu)
	if err != nil {
		return nil, fmt.Errorf("api: bad proxy url %q: %w", pu, err)
	}
	host := u.Host
	if u.Port() == "" {
		if u.Scheme == "http" {
			host += ":80"
		} else {
			host += ":443"
		}
	}
	conn, err := net.Dial("tcp", host)
	if err != nil {
		return nil, fmt.Errorf("api: proxy dial %s: %w", host, err)
	}
	conn.SetDeadline(time.Now().Add(20 * time.Second))
	fmt.Fprintf(conn, "CONNECT %s HTTP/1.1\r\nHost: %s\r\n\r\n", addr, addr)
	// Read the CONNECT response byte-by-byte: any buffered read could pull
	// the tunneled TLS ServerHello into a discarded buffer.
	var head []byte
	one := make([]byte, 1)
	for !bytes.HasSuffix(head, []byte("\r\n\r\n")) {
		n, err := conn.Read(one)
		if err != nil {
			conn.Close()
			return nil, fmt.Errorf("api: proxy CONNECT %s: %w", addr, err)
		}
		head = append(head, one[:n]...)
		if len(head) > 8192 {
			conn.Close()
			return nil, fmt.Errorf("api: proxy CONNECT %s: oversized response", addr)
		}
	}
	status := string(head[:13])
	if !strings.HasPrefix(status, "HTTP/1.1 200") && !strings.HasPrefix(status, "HTTP/1.0 200") {
		conn.Close()
		return nil, fmt.Errorf("api: proxy CONNECT %s: %s", addr, strings.SplitN(status, "\r", 2)[0])
	}
	return tlsfingerprint.HandshakeTLS(conn, serverName)
}

// qtIndentedJSON renders a JSON object the way Qt's
// QJsonDocument::toJson(QJsonDocument::Indented) does on the wire:
// "{\n" + 4-space-indented "key": value lines separated by ",\n" + "\n}\n".
// The stock client sends exactly this (captured byte-for-byte: the login
// body is 486 bytes indented vs 460 compact, Content-Length matches the
// indented length). Fields keep insertion order.
func qtIndentedJSON(fields [][2]string) []byte {
	var b bytes.Buffer
	b.WriteString("{\n")
	for i, kv := range fields {
		if i > 0 {
			b.WriteString(",\n")
		}
		val, err := json.Marshal(kv[1])
		if err != nil {
			panic(err) // static string fields, never fails
		}
		fmt.Fprintf(&b, "    %s: %s", strconv.Quote(kv[0]), val)
	}
	b.WriteString("\n}\n")
	return b.Bytes()
}

// loginPost writes one HTTP/1.1 POST byte-for-byte in the stock client's
// format (header order + Connection: Keep-Alive), reads the full response,
// and returns the (gzip-decoded) body. The connection stays alive for the
// next request, mirroring QNetworkAccessManager's connection reuse.
// uaLast selects between the two stock header orders: the pre-check
// endpoints put User-Agent last, the login POST puts it after
// Content-Type.
func loginPost(conn net.Conn, path, contentType, userAgent string, uaLast bool, body []byte) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "POST %s HTTP/1.1\r\n", path)
	fmt.Fprintf(&b, "Host: benshulinux.org:8443\r\n")
	fmt.Fprintf(&b, "Content-Type: %s\r\n", contentType)
	if !uaLast {
		fmt.Fprintf(&b, "User-Agent: %s\r\n", userAgent)
	}
	fmt.Fprintf(&b, "Content-Length: %d\r\n", len(body))
	fmt.Fprintf(&b, "Connection: Keep-Alive\r\n")
	fmt.Fprintf(&b, "Accept-Encoding: gzip, deflate\r\n")
	fmt.Fprintf(&b, "Accept-Language: en,*\r\n")
	if uaLast {
		fmt.Fprintf(&b, "User-Agent: %s\r\n", userAgent)
	}
	b.WriteString("\r\n")
	b.Write(body)
	if _, err := conn.Write(b.Bytes()); err != nil {
		return nil, err
	}
	resp, err := http.ReadResponse(bufio.NewReader(conn), nil)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	rbody := resp.Body
	if resp.Header.Get("Content-Encoding") == "gzip" {
		gz, err := gzip.NewReader(resp.Body)
		if err != nil {
			return nil, err
		}
		defer gz.Close()
		rbody = gz
	}
	payload, err := io.ReadAll(rbody)
	if err != nil {
		return nil, err
	}
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("HTTP %d: %s", resp.StatusCode, truncate(payload, 200))
	}
	return payload, nil
}

